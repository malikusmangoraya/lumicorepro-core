"""License injector — stamps every generated project with a sell-ready license.

Free + self-hosted: no licensing SaaS. Writes:
  - LICENSE.md                 (end-customer license: usage rights + warranty)
  - LICENSE-SEAL.md            (origin proof: generator name, signature)
  - frontend/src/config/license-config.js  (frontend may read status/branding)

Markers: idempotent — re-running on the same project never duplicates blocks.
"""
import os
from typing import Dict, Any, List

from utils.logger import agent_logger

MARKER = "LUMICORE_LICENSE"


class LicenseInjector:
    """Stamps sell-ready license artifacts into a generated project."""

    def __init__(self, seller: str = "LumicorePro Core Generator"):
        self.seller = seller

    def generate(self, spec: Dict[str, Any], project_dir: str) -> Dict[str, Any]:
        artifacts: List[str] = []

        license_path = os.path.join(project_dir, "LICENSE.md")
        license_md = self._build_license_md(spec)
        if self._write_marked(license_path, license_md):
            artifacts.append(license_path)

        seal_path = os.path.join(project_dir, "LICENSE-SEAL.md")
        seal_md = self._build_seal_md(spec)
        if self._write_marked(seal_path, seal_md):
            artifacts.append(seal_path)

        cfg_dir = os.path.join(project_dir, "frontend", "src", "config")
        os.makedirs(cfg_dir, exist_ok=True)
        cfg_path = os.path.join(cfg_dir, "license-config.js")
        cfg_js = self._build_config_js(spec)
        if self._write_marked(cfg_path, cfg_js):
            artifacts.append(cfg_path)

        agent_logger.info(f"LicenseInjector: stamped {len(artifacts)} artifact(s)")
        return {
            "artifacts": artifacts,
            "license_status": "trial_or_full",
            "seller": self.seller,
            "stamped": len(artifacts),
        }

    def _write_marked(self, path: str, content: str) -> bool:
        """Idempotent write guarded by LUMICORE_LICENSE markers."""
        existing = ""
        if os.path.exists(path):
            with open(path, "r", encoding="utf-8", errors="ignore") as fh:
                existing = fh.read()
            if MARKER in existing:
                return False

        body = (
            f"<!-- {MARKER}:START --><!-- generated by {self.seller} -->{content}"
            f"<!-- {MARKER}:END -->"
        )
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(body)
        return True

    def _build_license_md(self, spec: Dict[str, Any]) -> str:
        name = spec.get("project_name") or spec.get("name") or "LumicorePro Project"
        return (
            f"\n# License — {name}\n\n"
            "## Permitted Use\n"
            "- You may host, deploy, and commercially operate the generated website.\n"
            "- You may modify the generated source files for your own projects.\n"
            "- Reselling the generator's own templates/dependencies in source form "
            "requires a separate license.\n\n"
            "## Warranty\n"
            "- Provided “as-is”, without warranty of any kind (see DISCLAIMER in README).\n"
            "- The generator's AI output is a starting point; you are responsible for "
            "legal/service compliance of the final product.\n\n"
            "## AI Content Disclosure\n"
            "- This project was scaffolded by " + self.seller + " (" 
            + (spec.get("generator_version") or "v1.0") + ") using AI-assisted code "
            "generation. Review generated code before production use.\n"
        )

    def _build_seal_md(self, spec: Dict[str, Any]) -> str:
        return (
            f"\n# License Seal\n\n"
            f"- Generator: **{self.seller}**\n"
            f"- Project: {spec.get('project_name') or spec.get('name') or 'N/A'}\n"
            f"- Website type: {spec.get('website_type', 'business')}\n"
            f"- Industry: {spec.get('industry', 'general')}\n"
            f"- Generated at: {spec.get('generated_at') or 'timestamp injected at build'}\n\n"
            "This seal confirms the project originated from the LumicorePro generator. "
            "For commercial rights of commercial templates, upgrade when revenue starts.\n"
        )

    def _build_config_js(self, spec: Dict[str, Any]) -> str:
        return (
            "\n// Frontend license config (injected by generator, idempotent).\n"
            "const generatedLicense = {\n"
            "  status: 'trial_or_full',\n"
            "  seller: " + repr(self.seller) + ",\n"
            "  product: " + repr(spec.get("product_code") or "lumicorepro-core") + ",\n"
            "  aiGenerated: true,\n"
            "  watermark: true,\n"
            "};\n\n"
            "export { generatedLicense };\n"
        )


def inject_license(spec: Dict[str, Any], project_dir: str) -> Dict[str, Any]:
    """Convenience wrapper used by the orchestrator Phase 12 group."""
    return LicenseInjector().generate(spec, project_dir)


license_injector = LicenseInjector()