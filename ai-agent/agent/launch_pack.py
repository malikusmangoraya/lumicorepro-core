def pick_niche(spec: dict) -> str:
    """Detect the buyer's niche from the generation spec."""
    guess = str(spec.get("industry") or spec.get("website_type") or "").lower()
    niche = guess.strip()
    for key in NICHES:
        if key in niche:
            return key
    if niche in ("shop", "store", "retail", "marketplace", "shopping"):
        return "ecommerce"
    if niche in ("clinic", "medical", "doctor", "hospital", "dental"):
        return "healthcare"
    if niche in ("gym", "gymnasium", "training", "wellness", "sports"):
        return "fitness"
    return "ecommerce"


def generate_launch_pack(project_dir, spec):
    """Write production-seed.js, SETUP_GUIDE.md and LICENSE_NOTICE.txt."""
    project_dir = Path(project_dir)
    project_dir.mkdir(parents=True, exist_ok=True)
    niche = pick_niche(spec)
    meta = NICHES[niche]
    project_name = str(spec.get("project_name") or spec.get("name") or "My Business Website")
    today = date.today().isoformat()

    if niche == "healthcare":
        model_imports = "import Doctor from '../models/Doctor.js';\nimport Service from '../models/Service.js';\nimport Booking from '../models/Booking.js';"
        nickname = "doctors"
    elif niche == "fitness":
        model_imports = "import Plan from '../models/Plan.js';"
        nickname = "memberships"
    else:
        model_imports = "import Product from '../models/Product.js';\nimport Review from '../models/Review.js';\nimport Order from '../models/Order.js';\nimport Coupon from '../models/Coupon.js';"
        nickname = "products"

    seed_body = SEED_TEMPLATE.format(
        niche_label=meta["label"],
        niche=niche,
        products_note=meta["products_note"],
        model_imports=model_imports,
        niche_items_json=json.dumps([], indent=2),
    )

    (project_dir / "backend" / "scripts").mkdir(parents=True, exist_ok=True)
    (project_dir / "backend" / "scripts" / "production-seed.js").write_text(seed_body, encoding="utf-8")
    (project_dir / "SETUP_GUIDE.md").write_text(
        SETUP_GUIDE_TEMPLATE.format(
            project_name=project_name,
            date=today,
            niche_label=meta["label"],
            niche_line=meta["products_note"],
        ),
        encoding="utf-8",
    )
    (project_dir / "LICENSE_NOTICE.txt").write_text(
        LICENSE_NOTICE_TEMPLATE.format(project_name=project_name, date=today),
        encoding="utf-8",
    )

    return {
        "niche": niche,
        "label": meta["label"],
        "files": [
            "backend/scripts/production-seed.js",
            "SETUP_GUIDE.md",
            "LICENSE_NOTICE.txt",
        ],
    }


