# Sanity: every locale must cover exactly the same key set.
_KEY_SETS = {loc: frozenset(TRANSLATIONS[loc]) for loc in LOCALES}
_CANONICAL = _KEY_SETS[LOCALES[0]]
assert all(keys == _CANONICAL for keys in _KEY_SETS.values()), (
    "locale key sets differ: "
    + ", ".join(
        f"{loc}={len(_KEY_SETS[loc] ^ _CANONICAL)} mismatched"
        for loc in LOCALES
        if _KEY_SETS[loc] != _CANONICAL
    )
)
TOTAL_STRINGS = len(_CANONICAL)


def has_locale(locale: str) -> bool:
    """True when the pack can fully translate this locale."""
    return locale in TRANSLATIONS


def translate(locale: str, english: str) -> str | None:
    """Return the reviewed translation, or None when the pack has no entry.

    A returned value may legitimately equal `english` — that is a reviewed
    cognate (French "Contact", Spanish "No"), not a missing translation.
    """
    if not isinstance(english, str) or not english.strip():
        return None
    return TRANSLATIONS.get(locale, {}).get(english.strip())


def is_untranslatable(english: str) -> bool:
    """True for values that must stay identical in every locale."""
    return isinstance(english, str) and english.strip() in NON_TRANSLATABLE


def is_correct_as_english(locale: str, english: str) -> bool:
    """True when leaving this value byte-identical to English is correct.

    Three legitimate cases, and only these:
      * the value is a proper noun / address / e-mail / numeral
        (NON_TRANSLATABLE),
      * the target-language word is spelled the same (SAME_AS_ENGLISH),
      * the pack's own translation is spelled the same (a reviewed cognate:
        French "Contact", Spanish "No", German "Filter").

    This is the single predicate shared by the generator, the backfill script
    and the sellability audit, so all three agree on what "untranslated" means.
    """
    text = (english or "").strip()
    if not text:
        return True
    if text in NON_TRANSLATABLE:
        return True
    if (locale, text) in SAME_AS_ENGLISH:
        return True
    replacement = TRANSLATIONS.get(locale, {}).get(text)
    return replacement is not None and replacement.strip() == text


def needs_translation(locale: str, english: str) -> bool:
    """True when a value identical to `english` is a real translation gap."""
    return not is_correct_as_english(locale, english)
