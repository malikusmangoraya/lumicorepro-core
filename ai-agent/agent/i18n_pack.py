#!/usr/bin/env python3
"""Translation pack — the agent's single source of truth for UI localisation.

The localization engine builds every locale by overlaying a translation table
on an English base. When a key had no overlay the English value shipped as-is,
which is how a generated product ended up advertising 14 locales while showing
English buttons ("Save", "Delete", "Next", "Read More") inside an Arabic, Urdu
or Japanese page. This pack is the completion layer: any base value still equal
to its English source is replaced with the reviewed translation here.

It covers the 13 core locales the engine actually translates, for both the
shared UI vocabulary and the industry sections (restaurant, healthcare,
education, ecommerce).

Structure
---------
TRANSLATIONS[locale][english] = translation

NON_TRANSLATABLE holds values that must stay byte-identical in every locale:
brand names, press logos, postal addresses, phone numbers, e-mail addresses
and pure numerals/symbols.

SAME_AS_ENGLISH holds (locale, english) pairs where the target-language word
is genuinely spelled the same as English, so a value matching English is
correct rather than an oversight. Without this list an honest audit would flag
correct German "Information" as untranslated.

Consumers
---------
  * agent/localization_engine.py — completion layer at generation time
  * scripts/i18n_fill_locales.py — backfills already-generated products
  * scripts/audit_products.py    — the i18n-translated gate
"""

