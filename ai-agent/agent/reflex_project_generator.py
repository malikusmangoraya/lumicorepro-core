"""Generate a minimal, isolated Reflex app scaffold."""

import json
import re
from pathlib import Path
from typing import Dict


_REFLEX_IMPORT_ERROR = (
    'Reflex mode requires the optional Reflex dependency. '
    'Install it in the generated project with: python -m pip install -r requirements.txt'
)


REFLEX_VERSION = "0.10.0"
_PROJECT_NAME = re.compile(r"^[a-z][a-z0-9_]{0,49}$")


class ReflexGenerationError(RuntimeError):
    """Raised when a Reflex project cannot be safely generated."""


class ReflexProjectGenerator:
    """Write a minimal Reflex app without importing or installing Reflex."""

    def generate(
        self,
        destination_dir: str,
        project_name: str,
        *,
        validate_runtime: bool = False,
    ) -> Dict[str, str]:
        if not _PROJECT_NAME.fullmatch(project_name or ""):
            raise ReflexGenerationError(
                "Invalid project name; use 1-50 lowercase letters, digits, or underscores, starting with a letter."
            )

        if validate_runtime:
            try:
                __import__('reflex')
            except (ImportError, ModuleNotFoundError) as exc:
                raise ReflexGenerationError(_REFLEX_IMPORT_ERROR) from exc

        destination = Path(destination_dir).expanduser().resolve()
        if destination.exists() and (not destination.is_dir() or any(destination.iterdir())):
            raise ReflexGenerationError(f"Destination is not empty: {destination}")

        package_dir = destination / project_name
        try:
            destination.mkdir(parents=True, exist_ok=True)
            package_dir.mkdir()
            (package_dir / "__init__.py").write_text("", encoding="utf-8")
            (package_dir / f"{project_name}.py").write_text(
                "import reflex as rx\n\n\n"
                "class State(rx.State):\n"
                "    count: int = 0\n\n"
                "    @rx.event\n"
                "    def increment(self):\n"
                "        self.count += 1\n\n\n"
                "def index():\n"
                "    return rx.vstack(\n"
                "        rx.heading('Hello from Reflex'),\n"
                "        rx.text(State.count),\n"
                "        rx.button('Increment', on_click=State.increment),\n"
                "    )\n\n\n"
                "app = rx.App()\n"
                "app.add_page(index)\n",
                encoding="utf-8",
            )
            (destination / "rxconfig.py").write_text(
                "import reflex as rx\n\nconfig = rx.Config(app_name='" + project_name + "')\n",
                encoding="utf-8",
            )
            (destination / "requirements.txt").write_text(
                f"reflex=={REFLEX_VERSION}\n", encoding="utf-8"
            )
            (destination / "README.md").write_text(
                f"# {project_name}\n\n"
                "Minimal Reflex app generated by LumicorePro. Uses the Reflex Python package; "
                "no database, auth, or deployment integration is configured.\n\n"
                "## Run locally\n\n"
                "Use Python 3.11+ and create a virtual environment, then run:\n\n"
                "```bash\n"
                "python -m pip install -r requirements.txt\n"
                "reflex init\n"
                "reflex run\n"
                "```\n",
                encoding="utf-8",
            )
            report = {"framework": "reflex", "status": "created", "project_name": project_name}
            (destination / "generation-report.json").write_text(
                json.dumps(report, indent=2) + "\n", encoding="utf-8"
            )
        except (OSError, FileExistsError) as exc:
            raise ReflexGenerationError(f"Could not create Reflex project: {exc}") from exc
        return report
