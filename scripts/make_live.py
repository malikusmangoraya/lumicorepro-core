#!/usr/bin/env python3
"""Make every product in `products/` genuinely deployable.

Three things are wrong with the shipped configuration and this script repairs
all three, per product:

1.  `vite.config.js` hard-codes `base: './'`. That is fine when the bundle is
    served from a domain root, but GitHub Pages project sites are served from
    a sub-path, so every asset URL resolves one level too high. The base is
    replaced with an env-driven value that defaults to '/'.

2.  `public/404.html` is a *stale copy of a previous build* that hard-codes
    hashed asset filenames. After any rebuild it references files that no
    longer exist, which is why deep links such as /pricing 404 on Pages. It is
    removed and replaced by a post-build step that regenerates the fallback
    from the freshly built `index.html`.

3.  The CI workflow runs `npm ci` at the repository root, which has no
    package.json, and hides failures behind `|| true`. A green pipeline in
    that state proves nothing. It is rewritten to install and build in the
    right directories with nothing masked.

Usage:
    python scripts/make_live.py --dry-run
    python scripts/make_live.py
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass

ROOT = Path(__file__).resolve().parent.parent
PRODUCTS = ROOT / "products"

POSTBUILD_MARKER = "// generated by postbuild-spa-fallback"

# Regenerates dist/404.html from the built index.html. On GitHub Pages, any
# unknown path is served with 404.html; pointing that at the real application
# shell lets the client-side router take over and deep links keep working.
POSTBUILD_SCRIPT = f"""#!/usr/bin/env node
/**
 * Regenerate dist/404.html from the freshly built dist/index.html.
 *
 * GitHub Pages serves 404.html for any path it does not recognise. Copying the
 * real application shell there means a deep link such as /pricing loads the
 * app, and React Router renders the correct route instead of a 404 page.
 *
 * {POSTBUILD_MARKER}
 */
import {{ copyFileSync, existsSync, mkdirSync }} from 'node:fs';
import {{ dirname, resolve }} from 'node:path';
import {{ fileURLToPath }} from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dist = resolve(here, '..', 'dist');
const index = resolve(dist, 'index.html');
const notFound = resolve(dist, '404.html');

if (!existsSync(index)) {{
  console.error('[spa-fallback] dist/index.html not found — did the build run?');
  process.exit(1);
}}
if (!existsSync(dist)) {{
  mkdirSync(dist, {{ recursive: true }});
}}
copyFileSync(index, notFound);
console.log('[spa-fallback] wrote dist/404.html');
"""

PAGES_WORKFLOW = """# Deploy the live demo to GitHub Pages.
#
# GitHub Pages is a static host, so this publishes the built frontend. The
# backend is a separate Node service the buyer runs themselves — see
# DEPLOYMENT.md for the Docker and single-host instructions.
name: Deploy demo to GitHub Pages

on:
  push:
    branches: [main]
  workflow_dispatch:

permissions:
  contents: read
  pages: write
  id-token: write

# Never let two deploys race; always keep the newest commit live.
concurrency:
  group: github-pages
  cancel-in-progress: true

jobs:
  build:
    name: Build frontend
    runs-on: ubuntu-latest
    defaults:
      run:
        working-directory: frontend
    steps:
      - uses: actions/checkout@v4

      - name: Setup Node.js
        uses: actions/setup-node@v4
        with:
          node-version: '22'
          cache: npm
          cache-dependency-path: frontend/package-lock.json

      - name: Install dependencies
        run: npm ci

      - name: Build
        run: npm run build
        env:
          # Project Pages are served from https://<user>.github.io/<repo>/,
          # so every asset URL needs that prefix. Set VITE_BASE_PATH=/ when the
          # site is moved to a custom domain or a root-served host.
          VITE_BASE_PATH: /${{ github.event.repository.name }}/

      - name: Upload Pages artifact
        uses: actions/upload-pages-artifact@v3
        with:
          path: frontend/dist

  deploy:
    name: Publish
    needs: build
    runs-on: ubuntu-latest
    environment:
      name: github-pages
      url: ${{ steps.deployment.outputs.page_url }}
    steps:
      - name: Deploy to GitHub Pages
        id: deployment
        uses: actions/deploy-pages@v4
"""

CI_WORKFLOW = """# Continuous integration. Every job here must fail loudly: a red pipeline
# is useful, a green one that hides errors is not.
name: CI

on:
  push:
    branches: [main]
  pull_request:
    branches: [main]
  workflow_dispatch:

permissions:
  contents: read

jobs:
  frontend:
    name: Frontend — install and build
    runs-on: ubuntu-latest
    defaults:
      run:
        working-directory: frontend
    steps:
      - uses: actions/checkout@v4

      - uses: actions/setup-node@v4
        with:
          node-version: '22'
          cache: npm
          cache-dependency-path: frontend/package-lock.json

      - name: Install dependencies
        run: npm ci

      # The frontend has no unit-test runner configured; the production build
      # is the real gate, because it type-strips, bundles and fails on any
      # unresolved import or syntax error in the whole component tree.
      - name: Build
        run: npm run build

      - name: Verify the SPA fallback was generated
        run: test -f dist/404.html

      - uses: actions/upload-artifact@v4
        with:
          name: frontend-dist
          path: frontend/dist
          retention-days: 7

  backend:
    name: Backend — install and parse
    runs-on: ubuntu-latest
    defaults:
      run:
        working-directory: backend
    steps:
      - uses: actions/checkout@v4

      - uses: actions/setup-node@v4
        with:
          node-version: '22'
          cache: npm
          cache-dependency-path: backend/package-lock.json

      - name: Install dependencies
        run: npm ci

      # Parse every backend module with Node's ESM parser. This catches the
      # class of defect where a file does not load at runtime, without needing
      # a database or any running service.
      - name: Parse every backend module
        run: |
          set -euo pipefail
          tmp="$(mktemp -d)"
          count=0
          while IFS= read -r -d '' f; do
            cp "$f" "$tmp/probe.mjs"
            if ! node --check "$tmp/probe.mjs"; then
              echo "::error file=$f::does not parse"
              exit 1
            fi
            count=$((count + 1))
          done < <(find . -name '*.js' -not -path './node_modules/*' -print0)
          echo "Parsed $count backend modules successfully."

      - name: Boot the API and probe /health
        env:
          NODE_ENV: test
          JWT_SECRET: ci-placeholder-secret-ci-placeholder-secret
        run: |
          set -euo pipefail
          node server.js &
          pid=$!
          trap 'kill $pid 2>/dev/null || true' EXIT
          for i in $(seq 1 30); do
            if curl -fsS http://127.0.0.1:${PORT:-5000}/health > /dev/null; then
              echo "API responded to /health"
              exit 0
            fi
            sleep 1
          done
          echo "::error::API did not become healthy in 30s"
          exit 1
"""


@dataclass
class Report:
    name: str
    changes: list[str] = field(default_factory=list)
    skipped: list[str] = field(default_factory=list)


def set_vite_base(fe: Path, dry: bool) -> tuple[str, str]:
    """Replace a hard-coded relative base with an env-driven one."""
    cfg = fe / "vite.config.js"
    if not cfg.is_file():
        cfg = fe / "vite.config.ts"
    if not cfg.is_file():
        return "skip", "no vite config"
    text = cfg.read_text(encoding="utf-8", errors="replace")
    if "VITE_BASE_PATH" in text:
        return "skip", "already env-driven"

    if re.search(r"base\s*:\s*['\"][^'\"]*['\"]\s*,?", text):
        # Consume any trailing comma so the replacement cannot produce ",,".
        new = re.sub(
            r"base\s*:\s*['\"][^'\"]*['\"]\s*,?",
            "base: process.env.VITE_BASE_PATH || '/',",
            text, count=1,
        )
    elif re.search(r"^\s*plugins\s*:", text, re.M):
        # No base key at all: insert one above plugins, inside defineConfig.
        new = re.sub(r"(\n)(\s*)plugins\s*:",
                     r"\1\2base: process.env.VITE_BASE_PATH || '/',\1\2plugins:",
                     text, count=1, flags=re.M)
    else:
        return "skip", "could not find an insertion point in the vite config"

    if new == text:
        return "skip", "vite config unchanged"
    if not dry:
        cfg.write_text(new, encoding="utf-8")
    return "ok", "vite base is now env-driven (VITE_BASE_PATH)"


def add_postbuild(fe: Path, dry: bool) -> tuple[str, str]:
    """Add the script that regenerates dist/404.html after every build."""
    scripts_dir = fe / "scripts"
    target = scripts_dir / "postbuild-spa-fallback.mjs"
    if not dry:
        scripts_dir.mkdir(parents=True, exist_ok=True)
        if not target.exists():
            target.write_text(POSTBUILD_SCRIPT, encoding="utf-8")

    pj = fe / "package.json"
    if not pj.is_file():
        return "skip", "no frontend/package.json"
    data = json.loads(pj.read_text(encoding="utf-8"))
    build = data.get("scripts", {}).get("build", "")
    if "postbuild-spa-fallback" in build:
        return "skip", "build script already chains the SPA fallback"
    data.setdefault("scripts", {})["build"] = f"{build} && node scripts/postbuild-spa-fallback.mjs".strip()
    if not dry:
        pj.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    return "ok", "build now regenerates dist/404.html"


def remove_stale_404(fe: Path, dry: bool) -> tuple[str, str]:
    """Delete the stale prebuilt fallback that hard-codes old asset hashes."""
    stale = fe / "public" / "404.html"
    if not stale.is_file():
        return "skip", "no stale 404.html"
    if not dry:
        stale.unlink()
    return "ok", "removed stale public/404.html (hard-coded old asset hashes)"


def add_nojekyll(fe: Path, dry: bool) -> tuple[str, str]:
    """Stop GitHub Pages from running Jekyll and stripping _underscore dirs."""
    f = fe / "public" / ".nojekyll"
    if f.is_file():
        return "skip", ".nojekyll already present"
    if not dry:
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text("", encoding="utf-8")
    return "ok", "added public/.nojekyll"


def write_workflows(proj: Path, dry: bool) -> tuple[str, str]:
    wf = proj / ".github" / "workflows"
    pages, ci = wf / "deploy.yml", wf / "ci.yml"
    touched = []
    if not dry:
        wf.mkdir(parents=True, exist_ok=True)
        pages.write_text(PAGES_WORKFLOW, encoding="utf-8")
        ci.write_text(CI_WORKFLOW, encoding="utf-8")
    touched += [pages.name, ci.name]
    return "ok", f"rewrote {', '.join(touched)}"


def process(proj: Path, dry: bool) -> Report:
    rep = Report(name=proj.name)
    fe = proj / "frontend"
    if not fe.is_dir():
        rep.skipped.append("no frontend/")
        return rep
    for fn, args in (
        (set_vite_base, (fe, dry)),
        (add_postbuild, (fe, dry)),
        (remove_stale_404, (fe, dry)),
        (add_nojekyll, (fe, dry)),
        (write_workflows, (proj, dry)),
    ):
        status, detail = fn(*args)
        (rep.changes if status == "ok" else rep.skipped).append(f"{fn.__name__}: {detail}")
    return rep


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--only")
    a = ap.parse_args()

    if not PRODUCTS.is_dir():
        print(f"No {PRODUCTS} directory", file=sys.stderr)
        return 2
    dirs = sorted(q for q in PRODUCTS.iterdir() if q.is_dir() and not q.name.startswith("."))
    if a.only:
        dirs = [q for q in dirs if a.only in q.name]
    if not dirs:
        print("No matching products", file=sys.stderr)
        return 2

    print(f"=== make_live: {'DRY RUN' if a.dry_run else 'APPLY'} ({len(dirs)} product(s)) ===")
    for d in dirs:
        rep = process(d, a.dry_run)
        print(f"-- {rep.name}")
        for c in rep.changes:
            print(f"     [ok  ] {c}")
        for s in rep.skipped:
            print(f"     [skip] {s}")
    print(f"\n=== {len(dirs)} product(s) processed ===")
    return 0


if __name__ == "__main__":
    sys.exit(main())